"""Document ingestion and evidence-bearing figure extraction.

Supports PDF (via pdfplumber + PyMuPDF for page lookup), XLSX and CSV.
The extractor is deliberately conservative: if a figure cannot be located it is
returned as "not found" rather than guessed. Every located Figure carries a page and
the raw text snippet it was derived from.
"""

from __future__ import annotations

import csv
import re
from pathlib import Path
from typing import Iterable

from .models import Concept, Evidence, Figure

# Concept aliases anchored to the start of a table row. Anchoring is essential:
# unanchored "net sales" also matches narrative sentences like "the Company's net
# sales...", which would yield a meaningless percentage as the value.
CONCEPT_PATTERNS: dict[Concept, list[str]] = {
    Concept.REVENUE: [
        r"^total net sales\b",
    ],
    Concept.NET_INCOME: [
        r"^net income\b",
    ],
    Concept.TOTAL_ASSETS: [
        r"^total assets\b",
    ],
    Concept.TOTAL_LIABILITIES: [
        r"^total liabilities\b(?!\s+and)",   # exclude "Total liabilities and shareholders' equity"
    ],
    Concept.OPERATING_CASH_FLOW: [
        r"^cash generated by operating activities\b",
        r"^net cash generated by operating activities\b",
        r"^cash flows from operating activities\b",
    ],
}

NUM_RE = re.compile(r"\(?\d[\d,]*\)?")


def _to_number(token: str) -> float | None:
    """Parse a numeric token; parentheses denote a negative value."""
    cleaned = token.replace(",", "")
    negative = cleaned.startswith("(") and cleaned.endswith(")")
    cleaned = cleaned.strip("()")
    try:
        value = float(cleaned)
    except ValueError:
        return None
    return -value if negative else value


def _snippet(text: str, width: int = 120) -> str:
    flat = " ".join(text.split())
    return flat[:width]


def extract_from_pdf(path: str | Path, concepts: Iterable[Concept] | None = None) -> list[Figure]:
    """Extract figures from a PDF, recording the page and source line for each.

    Strategy: scan each page's text line by line; when a line matches a concept label,
    take the first plausible numeric token on that line as the value. This works for
    the well-structured demo filing and is documented as layout-sensitive in v1.
    """
    import pdfplumber  # imported lazily so pure modules import without it

    path = Path(path)
    wanted = list(concepts) if concepts else list(CONCEPT_PATTERNS)
    found: dict[Concept, Figure] = {}
    periods = _detect_periods(path)

    with pdfplumber.open(str(path)) as pdf:
        for page_no, page in enumerate(pdf.pages, start=1):
            text = page.extract_text() or ""
            for line in text.splitlines():
                low = line.lower().strip()
                for concept in wanted:
                    if concept in found:
                        continue
                    for pattern in CONCEPT_PATTERNS[concept]:
                        if re.search(pattern, low):
                            tokens = NUM_RE.findall(line)
                            # Skip 4-digit years and small percentage tokens. Financial
                            # statement figures are large (millions); take the first
                            # such token, which is the most recent period column.
                            candidates: list[float] = []
                            for t in tokens:
                                if re.fullmatch(r"(19|20)\d{2}", t):
                                    continue
                                n = _to_number(t)
                                if n is not None and abs(n) >= 1000:
                                    candidates.append(n)
                            if not candidates:
                                continue
                            value = candidates[0]
                            period = periods[0] if periods else "FY"
                            found[concept] = Figure(
                                concept=concept,
                                value=value,
                                period=period,
                                evidence=Evidence(
                                    document=path.name,
                                    page=page_no,
                                    snippet=_snippet(line),
                                ),
                            )
                            break
                    if concept in found:
                        break
    return list(found.values())


def _detect_periods(path: Path) -> list[str]:
    """Best-effort detection of fiscal-year labels such as 2023, 2022, 2021."""
    try:
        import pymupdf  # PyMuPDF (modern import name; 'fitz' is deprecated)

        doc = pymupdf.open(str(path))
        text = doc[0].get_text()[:4000] if len(doc) else ""
        doc.close()
    except Exception:
        return []
    # Prefer the explicit fiscal-year-ended statement on the cover page; falling back
    # to a generic year scan risks picking up "2024 annual meeting" etc.
    m = re.search(r"fiscal\s+year\s+ended\s+\w+\s+\d{1,2},?\s+(20\d{2})", text, re.I)
    if m:
        fy = int(m.group(1))
        return [f"FY{fy}", f"FY{fy - 1}", f"FY{fy - 2}"]
    years = sorted(set(re.findall(r"\b20\d{2}\b", text)), reverse=True)
    return [f"FY{y}" for y in years[:3]]


def extract_from_table(path: str | Path) -> list[Figure]:
    """Extract figures from a CSV or XLSX where rows are concepts and columns are periods."""
    import pandas as pd

    path = Path(path)
    if path.suffix.lower() in {".xlsx", ".xls"}:
        df = pd.read_excel(path)
    else:
        df = pd.read_csv(path)

    figures: list[Figure] = []
    period_cols = [c for c in df.columns if str(c).lower() not in {"concept", "item", "metric"}]
    for _, row in df.iterrows():
        label = str(row.iloc[0]).lower()
        concept = _match_concept(label)
        if concept is None:
            continue
        latest_col = period_cols[-1] if period_cols else df.columns[1]
        value = _to_number(str(row[latest_col]))
        if value is None:
            continue
        figures.append(Figure(
            concept=concept,
            value=value,
            period=str(latest_col),
            evidence=Evidence(
                document=path.name,
                sheet=str(df.columns.name or "Sheet1"),
                snippet=f"{row.iloc[0]}: {row[latest_col]}",
            ),
        ))
    return figures


def _match_concept(label: str) -> Concept | None:
    for concept, patterns in CONCEPT_PATTERNS.items():
        if any(re.search(p, label) for p in patterns):
            return concept
    return None


def read_figures(path: str | Path) -> list[Figure]:
    """Dispatch to the appropriate reader based on file extension."""
    path = Path(path)
    suffix = path.suffix.lower()
    if suffix == ".pdf":
        return extract_from_pdf(path)
    if suffix in {".csv", ".xlsx", ".xls"}:
        return extract_from_table(path)
    raise ValueError(f"Unsupported file type: {suffix}")
